    /// Merge `src` into `dst`: re-point all edges, then delete src.
    pub async fn merge_node_into(&self, src: &str, dst: &str) -> Result<()> {
        tokio::task::block_in_place(|| {
            let mut conn = self.conn.blocking_lock();
            // M31 audit fix: 6 sequential statements re-pointing edges then
            // deleting src -- a crash mid-sequence left a "phantom" node with
            // some edges re-pointed and others still dangling on the deleted id.
            let tx = conn.transaction()?;
            // OR IGNORE: dst may already hold an identical edge (PK source,target,type) —
            // without it one collision aborts the whole merge (root cause of dedup never merging).
            tx.execute("UPDATE OR IGNORE edges SET source = ?2 WHERE source = ?1 AND target != ?2", params![src, dst])?;
            tx.execute("UPDATE OR IGNORE edges SET target = ?2 WHERE target = ?1 AND source != ?2", params![src, dst])?;
            // Drop src edges that collided (left in place by OR IGNORE) plus self-loops
            tx.execute("DELETE FROM edges WHERE source = ?1 OR target = ?1", params![src])?;
            tx.execute("DELETE FROM edges WHERE source = target", params![])?;
            tx.execute("DELETE FROM node_embeddings WHERE node_id = ?1", params![src])?;
            tx.execute("DELETE FROM nodes WHERE id = ?1", params![src])?;
            tx.commit()?;
            Ok::<(), anyhow::Error>(())
        })?;
        Ok(())
    }

    /// Flag source nodes conflicted when they have >1 distinct target for the same predicate.
    /// M35: applies temporal supersession — the edge with the most recent valid_from is the
    /// current truth; older edges get valid_until set to the superseding edge's valid_from
    /// (they remain in the DB but are no longer "current"). If ≥2 edges have the same
    /// valid_from and it's the maximum for the group, that is a genuine tie and the node
    /// is marked conflicted = 1 for human/agent review.
    pub async fn flag_contradiction_nodes(&self) -> Result<usize> {
        tokio::task::block_in_place(|| {
            let conn = self.conn.blocking_lock();

            // Fetch all edges (except related_to) ordered by source, type, valid_from
            let mut stmt = conn.prepare(
                "SELECT source, type, target, valid_from FROM edges
                 WHERE type != 'related_to'
                 ORDER BY source, type, valid_from ASC NULLS LAST"
            )?;
            let rows: Vec<(String, String, String, Option<i64>)> = stmt.query_map([], |row| {
                Ok((row.get(0)?, row.get(1)?, row.get(2)?, row.get(3)?))
            })?.filter_map(|r| r.ok()).collect();

            // Group edges by (source, type)
            let mut groups: EdgeGroupMap = std::collections::HashMap::new();
            for (src, typ, tgt, vf) in &rows {
                groups.entry((src.clone(), typ.clone())).or_default().push((tgt.clone(), *vf));
            }

            let mut conflict_count = 0usize;

            for ((src, typ), edge_list) in &groups {
                // Only process groups with >1 distinct target
                let distinct_targets: std::collections::HashSet<&str> =
                    edge_list.iter().map(|(t, _)| t.as_str()).collect();
                if distinct_targets.len() <= 1 { continue; }

                // Find max valid_from (NULLs treated as lowest)
                let max_vf = edge_list.iter()
                    .filter_map(|(_, vf)| *vf)
                    .max();

                match max_vf {
                    None => {
                        // All NULL valid_from — no temporal signal, flag as conflicted
                        conn.execute(
                            "UPDATE nodes SET conflicted = 1, updated_at = CURRENT_TIMESTAMP WHERE id = ?1 AND conflicted = 0",
                            params![src],
                        )?;
                        conflict_count += 1;
                    }
                    Some(max) => {
                        // Count edges at max valid_from
                        let at_max_count = edge_list.iter()
                            .filter(|(_, vf)| *vf == Some(max))
                            .count();

                        if at_max_count > 1 {
                            // Genuine tie — two edges claim the same most-recent time
                            conn.execute(
                                "UPDATE nodes SET conflicted = 1, updated_at = CURRENT_TIMESTAMP WHERE id = ?1 AND conflicted = 0",
                                params![src],
                            )?;
                            conflict_count += 1;
                        }

                        // Supersede older edges (valid_from < max OR NULL) — set valid_until = max
                        for (tgt, vf) in edge_list {
                            if *vf != Some(max) {
                                conn.execute(
                                    "UPDATE edges SET valid_until = ?1
                                     WHERE source = ?2 AND target = ?3 AND type = ?4 AND valid_until IS NULL",
                                    params![max, src, tgt, typ],
                                )?;
                            }
                        }
                    }
                }
            }

            Ok::<usize, anyhow::Error>(conflict_count)
        })
    }

