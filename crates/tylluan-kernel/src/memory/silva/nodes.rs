/// Node types that are generated by internal cognitive modules (GraphRAG, Consensus, AgentMemory).
/// These MUST NOT be created through the public API (HTTP ingest, tylluan_remember, guilds)
/// to prevent "drift de consolidación" — auto-generated summaries being re-ingested as facts.
pub const DRIFT_SENSITIVE_TYPES: &[&str] = &["summary", "synthesis", "agent_summary"];

