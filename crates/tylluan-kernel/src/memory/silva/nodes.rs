    /// Manual weight decay using half-life exponential formula.
    /// T_half = 14 days = 1_209_600 seconds.
    /// Decay a node using FSRS retrievability.
    /// Weight is derived from retrievability: R=2^(-elapsed_days / fsrs_stability).
    /// The node's fsrs_stability is also slightly reduced (passive decay).
    pub async fn decay_node(&self, id: &str, elapsed_secs: i64) -> Result<()> {
        tokio::task::block_in_place(|| {
            let conn = self.conn.blocking_lock();
            let elapsed_days = (elapsed_secs as f64 / 86400.0).max(0.0);

            let result: Result<(f64, f64, i64), _> = conn.query_row(
                "SELECT fsrs_stability, fsrs_difficulty, fsrs_last_review FROM nodes WHERE id = ?1",
                params![id],
                |row| Ok((row.get(0)?, row.get(1)?, row.get(2)?)),
            );
            if let Ok((stability, difficulty, last_review)) = result {
                let item = tylluan_fsrs::FsrsItem::with_params(stability, difficulty, last_review);
                let r = item.retrievability(elapsed_days);
                let new_weight = (r * 0.99 + 0.01).max(0.01);
                // Passive stability decay: -5% per 30 days
                let decayed_stability = (stability * 0.95_f64.powf(elapsed_days / 30.0))
                    .max(tylluan_fsrs::MIN_STABILITY_DAYS);
                conn.execute(
                    "UPDATE nodes SET weight = ?1, fsrs_stability = ?2, updated_at = CURRENT_TIMESTAMP WHERE id = ?3",
                    params![new_weight, decayed_stability, id],
                )?;
            }
            Ok::<(), anyhow::Error>(())
        })?;
        Ok(())
    }

    /// Detect communities (Louvain) and persist to node_communities.
    pub async fn detect_communities(&self) -> Result<HashMap<String, usize>> {
        let nodes = self.get_nodes_limited(1000, 0.0).await?;
        let edges = self.get_all_edges().await?;
        let node_ids: Vec<String> = nodes.iter().map(|n| n.id.clone()).collect();
        let mut graph = WeightedGraph::new(node_ids);
        for edge in edges {
            let source = edge.get("source").and_then(|v| v.as_str()).unwrap_or_default().to_string();
            let target = edge.get("target").and_then(|v| v.as_str()).unwrap_or_default().to_string();
            let weight = edge.get("weight").and_then(|v| v.as_f64()).unwrap_or(1.0);
            if !source.is_empty() && !target.is_empty() {
                graph.add_edge(&source, &target, weight);
            }
        }
        let communities = graph.find_communities();
        tokio::task::block_in_place(|| {
            let mut conn = self.conn.blocking_lock();
            // M31 audit fix: node_communities and nodes.cluster_id are two
            // separate tables updated in a loop -- a crash mid-loop left them
            // inconsistent (some nodes tagged in one table, not the other).
            let tx = conn.transaction()?;
            {
                let mut stmt = tx.prepare(
                    "INSERT INTO node_communities (node_id, cluster_id, updated_at)
                     VALUES (?1, ?2, CURRENT_TIMESTAMP)
                     ON CONFLICT(node_id) DO UPDATE SET cluster_id = excluded.cluster_id, updated_at = CURRENT_TIMESTAMP"
                )?;
                for (node_id, cluster_id) in &communities {
                    stmt.execute(params![node_id, *cluster_id as i64])?;
                }
                let mut stmt_node = tx.prepare("UPDATE nodes SET cluster_id = ?2 WHERE id = ?1")?;
                for (node_id, cluster_id) in &communities {
                    stmt_node.execute(params![node_id, *cluster_id as i64])?;
                }
            }
            tx.commit()?;
            Ok::<(), anyhow::Error>(())
        })?;
        Ok(communities)
    }

