import { ColoquioMessage } from '../components/coloquio-types';

export type AgUiToolStatus = 'running' | 'passed' | 'failed';

export interface AgUiToolCall {
  id: string;
  tool: string;
  guild?: string;
  intent?: string;
  performed?: string;
  changed?: string;
  status: AgUiToolStatus;
  rawJson?: string;
}

export type AgUiHandoffKind = 'delivery' | 'completed' | 'broadcast' | 'idle';

export interface AgUiHandoff {
  kind: AgUiHandoffKind;
  label: string;
  taskId?: string;
  fromAgent: string;
  toAgents: string[];
  deliveredTag?: boolean;
}

export interface AgUiParsedMessage {
  cleanContent: string;
  thoughtContent: string;
  toolCalls: AgUiToolCall[];
  handoff: AgUiHandoff | null;
  isPlan: boolean;
}

/**
 * Parses a ColoquioMessage into structured AG-UI / CopilotKit primitives
 * (Handoff metadata, Thinking traces, Tool Call / ACTION_REPORT cards, and HITL plans)
 * while maintaining 100% backward compatibility with plain Markdown turns.
 */
export function parseAgUiMessage(msg: ColoquioMessage): AgUiParsedMessage {
  let working = msg.content || '';
  let thoughtContent = '';
  const toolCalls: AgUiToolCall[] = [];
  let handoff: AgUiHandoff | null = null;

  // 1. Parse structured metadata if present
  let metaObj: Record<string, unknown>;
  try {
    metaObj = JSON.parse(msg.metadata || '{}') as Record<string, unknown>;
  } catch {
    metaObj = {};
  }

  if (typeof metaObj.thought === 'string' && metaObj.thought.trim()) {
    thoughtContent = metaObj.thought.trim();
  }

  if (Array.isArray(metaObj.tool_calls)) {
    metaObj.tool_calls.forEach((tc, idx) => {
      if (tc && typeof tc === 'object') {
        const rec = tc as Record<string, unknown>;
        const rawStatus = String(rec.status || 'passed').toLowerCase();
        const status: AgUiToolStatus =
          rawStatus === 'running' || rawStatus === 'inprogress' || rawStatus === 'executing'
            ? 'running'
            : rawStatus === 'failed' || rawStatus === 'error'
            ? 'failed'
            : 'passed';
        toolCalls.push({
          id: String(rec.id || `${msg.msg_id}-tc-${idx}`),
          tool: String(rec.tool || 'tylluan_do'),
          guild: typeof rec.guild === 'string' ? rec.guild : undefined,
          intent: typeof rec.intent === 'string' ? rec.intent : undefined,
          performed: typeof rec.performed === 'string' ? rec.performed : undefined,
          changed: typeof rec.changed === 'string' ? rec.changed : undefined,
          status,
          rawJson: JSON.stringify(rec, null, 2),
        });
      }
    });
  }

  // 2. Extract [PENSAMIENTO]...[/FIN PENSAMIENTO] or <think>...</think>
  const thoughtRegex = /\[PENSAMIENTO\]([\s\S]*?)(?:\[FIN PENSAMIENTO\]|$)/i;
  const thoughtMatch = working.match(thoughtRegex);
  if (thoughtMatch) {
    thoughtContent = (thoughtContent ? `${thoughtContent}\n` : '') + thoughtMatch[1].trim();
    working = working.replace(thoughtRegex, '').trim();
  }

  const xmlThinkRegex = /<think>([\s\S]*?)(?:<\/think>|$)/i;
  const xmlThinkMatch = working.match(xmlThinkRegex);
  if (xmlThinkMatch) {
    thoughtContent = (thoughtContent ? `${thoughtContent}\n` : '') + xmlThinkMatch[1].trim();
    working = working.replace(xmlThinkRegex, '').trim();
  }

  // 3. Extract inline ACTION_REPORT: { ... } blocks generated by Tylluan sovereign tools
  const actionReportRegex = /(?:---\s*\n)?ACTION_REPORT:\s*(\{[\s\S]*?\n\})(?:\s*\n---\s*\nRouting:\s*guild=([^\s\n]+)\s+tool=([^\s\n]+)(?:\s*\nRouting Trace:(?:\s*\n\s*-[^\n]+)*)?)?/g;
  let arMatch: RegExpExecArray | null;
  let arIndex = 0;
  while ((arMatch = actionReportRegex.exec(working)) !== null) {
    const jsonBlock = arMatch[1];
    const routedGuild = arMatch[2];
    const routedTool = arMatch[3];
    try {
      const parsed = JSON.parse(jsonBlock) as {
        changed?: string;
        intended?: string;
        performed?: string;
        verified?: { method?: string; status?: string };
      };
      const perfMatch = parsed.performed?.match(/guild='([^']+)'\s+tool='([^']+)'/);
      const guildName = routedGuild || perfMatch?.[1] || undefined;
      const toolName = routedTool || perfMatch?.[2] || 'tylluan_do';
      const vStatus = parsed.verified?.status?.toLowerCase();
      const isErr =
        vStatus === 'failed' ||
        vStatus === 'error' ||
        (parsed.changed && (parsed.changed.startsWith('❌') || parsed.changed.startsWith('Error')));

      toolCalls.push({
        id: `${msg.msg_id}-ar-${arIndex++}`,
        tool: toolName,
        guild: guildName,
        intent: parsed.intended,
        performed: parsed.performed,
        changed: parsed.changed,
        status: isErr ? 'failed' : 'passed',
        rawJson: JSON.stringify(parsed, null, 2),
      });
    } catch {
      // Leave malformed JSON alone
    }
  }
  if (arIndex > 0) {
    working = working.replace(actionReportRegex, '').trim();
  }

  // 4. Detect CoAgents Handoff / Fleet protocol headers at the start of the message
  const deliveredTag = /\|\s*T-Delivered\s*$/i.test(working);
  if (deliveredTag) {
    working = working.replace(/\s*\|\s*T-Delivered\s*$/i, '').trim();
  }

  // Pattern A: [AG-24 ENTREGADO -> @claude-code @jose] or [D-89 ENTREGADO → @claude-code]
  const deliveryHeaderMatch = working.match(
    /^\[([A-Z]+-\d+[A-Za-z0-9_-]*)\s+(ENTREGAD[OA]|PROPUESTA|COMPLETAD[OA]|LISTO)\s*(?:->|→)\s*([^\]]+)\]\s*/i
  );
  if (deliveryHeaderMatch) {
    const taskId = deliveryHeaderMatch[1].toUpperCase();
    const verb = deliveryHeaderMatch[2].toUpperCase();
    const targetsRaw = deliveryHeaderMatch[3];
    const toAgents = Array.from(targetsRaw.matchAll(/@([a-zA-Z0-9_-]+)/g)).map(m => m[1]);
    handoff = {
      kind: 'delivery',
      label: verb,
      taskId,
      fromAgent: msg.author_id,
      toAgents,
      deliveredTag: deliveredTag || true,
    };
  }

  // Pattern B: [Task Completed] T-DSH-170 — ...
  if (!handoff) {
    const taskCompletedMatch = working.match(
      /^\[Task Completed\]\s+([A-Z]+(?:-[A-Z0-9]+)+)\s*(?:—|--|-|:)?\s*/i
    );
    if (taskCompletedMatch) {
      handoff = {
        kind: 'completed',
        label: 'TASK COMPLETED',
        taskId: taskCompletedMatch[1].toUpperCase(),
        fromAgent: msg.author_id,
        toAgents: ['claude-code'],
        deliveredTag,
      };
    }
  }

  // Pattern C: [RESPONSABLE DEL CIERRE -> TODOS] or [RESPONSABLE DEL CIERRE]
  if (!handoff) {
    const coordinatorMatch = working.match(
      /^\[(RESPONSABLE DEL CIERRE|ORQUESTADOR|TECH LEAD)(?:\s*(?:->|→)\s*([^\]]+))?\]\s*/i
    );
    if (coordinatorMatch) {
      const targetStr = coordinatorMatch[2] || '';
      const mentioned = Array.from(working.matchAll(/@([a-zA-Z0-9_-]+)/g))
        .map(m => m[1])
        .filter((v, i, a) => a.indexOf(v) === i)
        .slice(0, 5);
      handoff = {
        kind: 'broadcast',
        label: coordinatorMatch[1].toUpperCase(),
        fromAgent: msg.author_id,
        toAgents: mentioned.length > 0 ? mentioned : targetStr ? [targetStr.trim().toLowerCase()] : [],
        deliveredTag,
      };
    }
  }

  // Pattern D: [dsh SIN TAREA] T-DSH-170 ...
  if (!handoff) {
    const idleMatch = working.match(/^\[([a-zA-Z0-9_-]+)\s+SIN TAREA\]\s*([A-Z]+(?:-[A-Z0-9]+)+)?/i);
    if (idleMatch) {
      handoff = {
        kind: 'idle',
        label: 'SIN TAREA · DISPONIBLE',
        taskId: idleMatch[2] ? idleMatch[2].toUpperCase() : undefined,
        fromAgent: msg.author_id,
        toAgents: ['claude-code'],
        deliveredTag,
      };
    }
  }

  // Only treat [PLAN] as an actionable HITL plan when it starts the message or a line,
  // avoiding false positives when a report mentions "planes [PLAN]" in prose (bug seen in T2413->T2414).
  const isPlan =
    Boolean(metaObj.is_plan) ||
    /(?:^|\n)\s*\[plan\](?:\s|:|$)/i.test(working);

  return {
    cleanContent: working,
    thoughtContent,
    toolCalls,
    handoff,
    isPlan,
  };
}
